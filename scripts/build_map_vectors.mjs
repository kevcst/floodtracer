/** Build exact display polygons ahead of publication. No scientific measurements are recomputed.
 * Usage: PYTHON=.venv/bin/python node scripts/build_map_vectors.mjs
 * Requires Node.js and Python with Pillow. Reuses the browser's contour worker unchanged.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const app = path.join(root, 'app'), output = path.join(app, 'data/vectors');
const manifestBytes = fs.readFileSync(path.join(app, 'data/manifest.json'));
const manifest = JSON.parse(manifestBytes);
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const workerCode = fs.readFileSync(path.join(app, 'vector-worker.js'), 'utf8');
const classesCode = fs.readFileSync(path.join(app, 'vector-classes.js'), 'utf8');
const exporterVersion = sha(workerCode + classesCode + fs.readFileSync(fileURLToPath(import.meta.url), 'utf8'));
let result;
const context = vm.createContext({self: {postMessage: value => { result = value; }}});
context.importScripts = (...files) => files.forEach(file => vm.runInContext(fs.readFileSync(path.join(app, file), 'utf8'), context));
vm.runInContext(classesCode, context);
vm.runInContext(workerCode, context);
fs.mkdirSync(output, {recursive: true});
const index = {format: 1, sourceManifestSha256: sha(manifestBytes), entries: {}};
let totalRaw = 0, totalCompressed = 0;
const python = process.env.PYTHON || 'python3';
const decode = 'import sys,struct; from PIL import Image; im=Image.open(sys.argv[1]).convert("RGBA"); sys.stdout.buffer.write(struct.pack(">II",*im.size)); sys.stdout.buffer.write(im.tobytes())';
for (const [zone, data] of Object.entries(manifest.zonas)) {
  const views = data.capas.serie.fechas.map(date => ({file:`agua_${date}.png`, view:'date', corners:data.capas.serie.esquinas}));
  for (const [file, view] of [['extension.png','extent'],['persistencia.png','persist'],['retiro.png','retreat'],['monte.png','forest']]) views.push({file, view, corners:data.capas.evento.esquinas});
  for (const {file, view, corners} of views) {
    const key = `${zone}/${file}`, mask = path.join(app, 'data', key);
    const classes = context.nisarVectorClasses(view, manifest.leyendas);
    const maskBytes = fs.readFileSync(mask);
    const sourceHash = sha(Buffer.concat([maskBytes, Buffer.from(JSON.stringify({corners, classes, exporterVersion}))]));
    const filename = `${zone}-${file.slice(0,-4)}-${sourceHash.slice(0,20)}.geojson.gz`;
    const target = path.join(output, filename);
    let raw;
    if (fs.existsSync(target)) raw = null;
    else {
      const decoded = execFileSync(python, ['-c', decode, mask], {maxBuffer: 128 * 1024 * 1024});
      const width = decoded.readUInt32BE(0), height = decoded.readUInt32BE(4);
      result = null;
      context.self.onmessage({data:{id:1, pixels:new Uint8Array(decoded.subarray(8)), width, height, corners, classes}});
      if (!result || result.error) throw new Error(`${key}: ${result?.error || 'No contour output'}`);
      // Exact coordinates and labels from the existing contour worker, without simplification.
      raw = Buffer.from(JSON.stringify(result.data));
      fs.writeFileSync(target, gzipSync(raw, {level:9}));
    }
    const compressedBytes = fs.statSync(target).size;
    // Read cached output metadata without decoding the source image again.
    const {gunzipSync} = await import('node:zlib');
    raw ||= gunzipSync(fs.readFileSync(target));
    const geojson = JSON.parse(raw);
    const rings = geojson.features.flatMap(f => f.geometry.coordinates.flat());
    const vertices = rings.reduce((n, ring) => n + ring.length, 0);
    index.entries[key] = {file:filename, sha256:sha(raw), compressedBytes, jsonBytes:raw.length,
      features:geojson.features.length, vertices, maskSha256:sha(maskBytes), corners,
      classes:classes.map(({label,rgb}) => ({label,rgb}))};
    totalRaw += raw.length; totalCompressed += compressedBytes;
    console.log(`${key}: ${vertices.toLocaleString()} vertices, ${(compressedBytes / 1024).toFixed(0)} KB compressed`);
  }
}
index.revision = sha(JSON.stringify(index));
index.totals = {files:Object.keys(index.entries).length, jsonBytes:totalRaw, compressedBytes:totalCompressed};
// Publish the index last; a failed build must not advertise incomplete outputs.
fs.writeFileSync(path.join(output, 'index.json'), JSON.stringify(index, null, 2) + '\n');
// Remove only obsolete files generated by this exporter, after the complete build succeeds.
const active = new Set(Object.values(index.entries).map(entry => entry.file));
for (const name of fs.readdirSync(output)) if (name.endsWith('.geojson.gz') && !active.has(name)) fs.unlinkSync(path.join(output, name));
console.log(`Prepared ${index.totals.files} views: ${(totalRaw / 1e6).toFixed(1)} MB JSON, ${(totalCompressed / 1e6).toFixed(1)} MB compressed. Revision ${index.revision.slice(0,12)}.`);
